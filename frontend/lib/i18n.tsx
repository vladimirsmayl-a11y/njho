export type TKey = keyof (typeof DICT)['ru'];

interface I18nContextType {
  lang: Lang;
  setLang: (lang: Lang) => void;
  t: (key: TKey) => string;
}

const I18nContext = createContext<I18nContextType | null>(null);

const STORAGE_KEY = 'lvs:lang';

export function I18nProvider({ children }: { children: React.ReactNode }) {
  const [lang, setLangState] = useState<Lang>('ru');

  useEffect(() => {
    let next: Lang = 'ru';
    try {
      const stored = window.localStorage.getItem(STORAGE_KEY);
      if (stored === 'ru' || stored === 'kz' || stored === 'en') next = stored;
    } catch {
      /* приватный режим */
    }
    setLangState(next);
    document.documentElement.lang = next;
  }, []);

  const setLang = useCallback((next: Lang) => {
    setLangState(next);
    document.documentElement.lang = next;
    try {
      window.localStorage.setItem(STORAGE_KEY, next);
    } catch {
      /* приватный режим */
    }
    // Сохраняем выбор в профиле, если пользователь авторизован.
    void fetch('/api/me', {
      method: 'PATCH',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({ language: next }),
      credentials: 'same-origin',
    }).catch(() => undefined);
  }, []);

  const t = useCallback(
    (key: TKey) => DICT[lang][key] ?? DICT.ru[key] ?? key,
    [lang],
  );

  const value = useMemo(() => ({ lang, setLang, t }), [lang, setLang, t]);

  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

